import Foundation

/// Простая проверка на сообщения о самоповреждении. Это страховка, а не диагностика.
enum Safety {
    private static let triggers = [
        "суицид", "самоубийств", "покончить с собой", "убить себя", "не хочу жить",
        "хочу умереть", "навредить себе", "порезать себя", "свести счёты", "свести счеты"
    ]

    static func isCrisis(_ text: String) -> Bool {
        let t = text.lowercased()
        return triggers.contains { t.contains($0) }
    }

    /// TODO: добавить номера служб помощи для своей страны.
    static let message = """
    Мне очень жаль, что тебе сейчас так тяжело. Ты важен(на), и ты не обязан(а) справляться в одиночку.
    Если есть угроза жизни — позвони в экстренную службу (112 или местный номер) или обратись к кому-то из близких прямо сейчас.
    Этот помощник не заменяет специалиста.
    """
}
