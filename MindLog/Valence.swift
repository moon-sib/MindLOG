import SwiftUI

/// Шкала приятности ощущений: от -1 (очень неприятные) до +1 (очень приятные).
/// Здесь же — подписи, цвета, параметры фигуры и списки слов.
enum Valence {
    static let labels = [
        "Очень неприятные", "Неприятные", "Отчасти неприятные", "Нейтральные",
        "Отчасти приятные", "Приятные", "Очень приятные"
    ]

    static func index(_ v: Double) -> Int {
        let c = min(1, max(-1, v))
        return Int(((c + 1) / 2 * 6).rounded())
    }

    static func label(_ v: Double) -> String { labels[index(v)] }

    // MARK: Фигура

    /// Глубина «лепестков» (5 штук) — растёт с приятностью.
    static func petals(_ v: Double) -> Double { 0.2 * max(v, 0) }
    /// Колючесть (8 острых зубцов) — растёт с неприятностью.
    static func jag(_ v: Double) -> Double { 0.14 * max(-v, 0) }

    // MARK: Цвет

    private static let stops: [(Double, (Double, Double, Double))] = [
        (-1.00, (0.55, 0.40, 0.95)),  // фиолетовый
        (-0.66, (0.35, 0.45, 0.95)),  // индиго
        (-0.33, (0.30, 0.62, 0.95)),  // синий
        ( 0.00, (0.55, 0.78, 0.88)),  // холодный голубой
        ( 0.33, (0.55, 0.90, 0.30)),  // зелёный
        ( 0.66, (1.00, 0.84, 0.25)),  // золотой
        ( 1.00, (1.00, 0.60, 0.25))   // оранжевый
    ]

    static func color(_ v: Double) -> Color {
        let x = min(1, max(-1, v))
        for i in 1..<stops.count {
            let (v0, c0) = stops[i - 1]
            let (v1, c1) = stops[i]
            if x <= v1 {
                let t = (x - v0) / (v1 - v0)
                return Color(red: c0.0 + (c1.0 - c0.0) * t,
                             green: c0.1 + (c1.1 - c0.1) * t,
                             blue: c0.2 + (c1.2 - c0.2) * t)
            }
        }
        let last = stops[stops.count - 1].1
        return Color(red: last.0, green: last.1, blue: last.2)
    }

    // MARK: Слова

    static func words(for v: Double) -> [String] {
        switch index(v) {
        case 0...2:
            return [
                "Тревога", "Беспокойство", "Грусть", "Раздражение", "Злость", "Обида",
                "Одиночество", "Разочарование", "Усталость", "Подавленность", "Стыд",
                "Страх", "Растерянность", "Перегруженность", "Опустошённость", "Безнадёжность"
            ]
        case 3:
            return [
                "Спокойствие", "Безразличие", "Равновесие", "Задумчивость", "Скука",
                "Отстранённость", "Сосредоточенность", "Любопытство", "Оцепенение", "Усталость"
            ]
        default:
            return [
                "Изумление", "Приятное волнение", "Удивление", "Энтузиазм", "Счастье",
                "Радость", "Храбрость", "Гордость", "Уверенность", "Надежда", "Веселье",
                "Довольство", "Облегчение", "Благодарность", "Удовлетворённость",
                "Спокойствие", "Умиротворённость"
            ]
        }
    }

    // MARK: Влияния

    static let influenceGroups: [[String]] = [
        ["Здоровье", "Фитнес", "Забота о себе", "Хобби и увлечения", "Личность и самоопределение", "Духовная жизнь"],
        ["Сообщество", "Семья", "Друзья", "Партнёр", "Свидания и личная жизнь"],
        ["Задачи", "Работа", "Образование", "Путешествия", "Погода", "Текущие события", "Деньги"]
    ]
}
